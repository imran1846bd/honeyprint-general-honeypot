"""
SD Card Simulation - Virtual SD card for file storage.

Simulates the SD card file system found on most 3D printers. Stores
uploaded G-code files and provides file listing/selection capabilities.
This is a key attack surface - adversaries may upload malicious G-code.
"""

import json
import os
import time
from hashlib import sha256
from dataclasses import dataclass
from pathlib import Path


@dataclass
class SDFile:
    """A file on the virtual SD card."""
    name: str
    size: int
    content: str = ""
    upload_time: float = 0.0
    last_print_time: float = 0.0


class SDCardSimulation:
    """Virtual SD card file system."""

    def __init__(self, storage_dir: str | None = None):
        self._files: dict[str, SDFile] = {}
        self._selected_file: str | None = None
        self._storage_dir = Path(storage_dir) if storage_dir else None
        self._upload_history: list[dict] = []
        self._init_default_files()
        self._load_persistent_files()

    def _init_default_files(self) -> None:
        """Pre-populate with realistic files for deception."""
        default_files = [
            ("benchy.gcode", self._generate_fake_gcode("benchy", 150)),
            ("calibration_cube.gcode",
             self._generate_fake_gcode("calibration_cube", 50)),
            ("phone_stand_v2.gcode",
             self._generate_fake_gcode("phone_stand", 200)),
        ]
        for name, content in default_files:
            self._files[name.upper()] = SDFile(
                name=name,
                size=len(content),
                content=content,
                upload_time=time.time() - 86400 * 3,
            )

    def _generate_fake_gcode(self, name: str, layers: int) -> str:
        """Generate realistic-looking G-code for deception."""
        lines = [
            f"; generated by PrusaSlicer 2.7.1 on 2026-03-15",
            f"; {name}",
            "; filament used [mm] = 4521.3",
            "; filament used [g] = 13.5",
            "; estimated printing time = 1h 23m",
            "",
            "M201 X500 Y500 Z100 E5000 ; max acceleration",
            "M203 X200 Y200 Z5 E50 ; max feedrate",
            "M204 P500 R1000 T500 ; acceleration",
            "M205 X8 Y8 Z0.4 E5 ; jerk limits",
            "M104 S210 ; set hotend temp",
            "M140 S60 ; set bed temp",
            "M190 S60 ; wait for bed",
            "M109 S210 ; wait for hotend",
            "G28 ; home all axes",
            "G29 ; auto bed leveling",
            "G92 E0 ; reset extruder",
            "G1 Z2.0 F3000 ; move z up",
            "G1 X5 Y20 F5000 ; move to start",
            "",
        ]
        # Generate some realistic layer G-code
        for layer in range(layers):
            z = 0.2 + layer * 0.2
            lines.append(f"; LAYER {layer}")
            lines.append(f"G1 Z{z:.3f} F600")
            lines.append(f"G1 X10 Y10 E{layer * 2:.4f} F1200")
            lines.append(f"G1 X50 Y10 E{layer * 2 + 0.5:.4f} F1200")
            lines.append(f"G1 X50 Y50 E{layer * 2 + 1.0:.4f} F1200")
            lines.append(f"G1 X10 Y50 E{layer * 2 + 1.5:.4f} F1200")
            lines.append(f"G1 X10 Y10 E{layer * 2 + 2.0:.4f} F1200")
        lines.append("")
        lines.append("; END GCODE")
        lines.append("M104 S0 ; hotend off")
        lines.append("M140 S0 ; bed off")
        lines.append("M84 ; disable motors")
        lines.append("M107 ; fan off")
        return "\n".join(lines)

    def list_files(self) -> list[dict]:
        """List all files on SD card (M20 response)."""
        result = []
        for key, f in sorted(self._files.items()):
            result.append({
                "name": f.name,
                "size": f.size,
                "display": f.name,
            })
        return result

    @staticmethod
    def _display_filename(filename: str) -> str:
        """Return the SD-card-visible filename for an uploaded file."""
        if len(filename) <= 12:
            return filename
        base = filename[:8]
        ext = filename.split(".")[-1][:3] if "." in filename else "GCO"
        return f"{base}.{ext}"

    def _resolve_key(self, filename: str) -> str | None:
        """Resolve either the internal key or displayed filename to a file key."""
        key = filename.upper()
        if key in self._files:
            return key
        for existing_key, file in self._files.items():
            if file.name.upper() == key:
                return existing_key
        return None

    def upload_file(self, filename: str, content: str) -> SDFile:
        """Upload a file to the SD card."""
        display_name = self._display_filename(filename)
        key = display_name.upper()
        uploaded = SDFile(
            name=display_name,
            size=len(content),
            content=content,
            upload_time=time.time(),
        )
        self._files[key] = uploaded
        self._persist_upload(filename, uploaded)
        return uploaded

    def delete_file(self, filename: str) -> bool:
        key = self._resolve_key(filename)
        if key:
            stored_name = self._files[key].name
            del self._files[key]
            if self._storage_dir:
                (self._storage_dir / "files" / self._safe_name(stored_name)).unlink(
                    missing_ok=True
                )
            return True
        return False

    def select_file(self, filename: str) -> bool:
        key = self._resolve_key(filename)
        if key:
            self._selected_file = key
            return True
        return False

    def get_selected_file(self) -> SDFile | None:
        if self._selected_file and self._selected_file in self._files:
            return self._files[self._selected_file]
        return None

    def get_file(self, filename: str) -> SDFile | None:
        key = self._resolve_key(filename)
        if key:
            return self._files[key]
        return None

    def get_file_content(self, filename: str) -> str | None:
        key = self._resolve_key(filename)
        if key:
            return self._files[key].content
        return None

    def get_file_count(self) -> int:
        return len(self._files)

    def get_total_size(self) -> int:
        return sum(f.size for f in self._files.values())

    def get_upload_history(self) -> list[dict]:
        return list(self._upload_history)

    @staticmethod
    def _safe_name(filename: str) -> str:
        return os.path.basename(filename).replace("/", "_").replace("\\", "_")

    def _load_persistent_files(self) -> None:
        if not self._storage_dir:
            return
        files_dir = self._storage_dir / "files"
        files_dir.mkdir(parents=True, exist_ok=True)
        history_path = self._storage_dir / "upload_history.jsonl"
        if history_path.exists():
            for line in history_path.read_text(encoding="utf-8").splitlines():
                try:
                    self._upload_history.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
        for path in files_dir.iterdir():
            if not path.is_file():
                continue
            content = path.read_text(encoding="utf-8", errors="replace")
            self._files[path.name.upper()] = SDFile(
                name=path.name,
                size=len(content),
                content=content,
                upload_time=path.stat().st_mtime,
            )

    def _persist_upload(self, original_name: str, uploaded: SDFile) -> None:
        if not self._storage_dir:
            return
        files_dir = self._storage_dir / "files"
        files_dir.mkdir(parents=True, exist_ok=True)
        safe_name = self._safe_name(uploaded.name)
        (files_dir / safe_name).write_text(uploaded.content, encoding="utf-8")
        history = {
            "original_filename": original_name,
            "stored_filename": uploaded.name,
            "size": uploaded.size,
            "content_hash": sha256(uploaded.content.encode()).hexdigest(),
            "timestamp": uploaded.upload_time,
        }
        self._upload_history.append(history)
        with (self._storage_dir / "upload_history.jsonl").open(
            "a", encoding="utf-8"
        ) as handle:
            handle.write(json.dumps(history) + "\n")
